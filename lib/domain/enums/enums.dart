/// 도메인 enum 정의.
///
/// **저장은 항상 `name` 문자열로 한다** (index 금지 — 순서를 바꾸면 기존 데이터가
/// 다른 값으로 읽힌다). 파싱은 `enumFromName` 이 모르는 값을 fallback 으로 흘린다.
library;

/// 읽을 수 있는 것의 종류. `Content.type` 이 책과 영상을 가른다.
///
/// 왜 하나의 엔티티로 합쳤나: 책과 영상은 "아이가 보고 듣는 것" 이라는 점이 같고
/// 플레이리스트·독서기록·통계가 둘을 구분 없이 다뤄야 한다.
enum ContentType {
  /// 페이지 사진 + 오디오로 이루어진 책.
  pagedBook,

  /// 촬영·가져온 동영상 (M4).
  video,

  /// 동요 · 이야기 음원 — 작은 음악방(2026-11-22). 넣기 · 재생은 다음 차례라 지금은 자리만 있다.
  ///
  /// 왜 지금 값을 넣나: 방 고르기가 종류로 목록을 나누므로 값이 먼저 있어야 한다.
  /// 맨 끝에 더한다 — 저장은 이름이라 순서가 상관없지만 읽는 사람이 헷갈리지 않게.
  audio,
}

/// 오디오 트랙의 출처. 한 페이지가 **여러 종류를 동시에** 보유한다.
///
/// 4종을 처음부터 정의하는 이유는 [1_DESIGN ADR-6] — 나중에 값을 추가하면
/// 저장 포맷 마이그레이션이 필요해진다. 구현은 마일스톤별로 나뉜다.
enum AudioSource {
  /// OS 내장 TTS 가 **런타임에 합성**한다. 파일이 없다(`path == null`). M1
  ///
  /// 텍스트만 있으면 항상 만들 수 있어 **최후의 폴백**이다.
  deviceTts,

  /// 보호자가 직접 읽어 녹음한 파일. M1 — 이 앱의 본질.
  parentRecording,

  /// 로컬 GPU 워커가 부모 목소리를 참조해 합성한 파일. M3
  aiClonedVoice,

  /// 로컬 GPU 워커가 기본 화자로 합성한 파일. 정의만 두고 당장 쓰지 않는다.
  aiNarration,
}

/// 등록된 목소리의 상태 (M3).
enum VoiceStatus {
  /// 샘플을 올리고 워커의 검증을 기다리는 중.
  pending,

  /// 검증 통과 — 이 목소리로 책 음원을 만들 수 있다.
  ready,

  /// 검증 실패 (샘플 품질 부족 등).
  failed,
}
